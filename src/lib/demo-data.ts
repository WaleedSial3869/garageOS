// Helper functions for demo data
export function getDemoCustomersWithStats(): CustomerWithStats[] {
  return demoCustomers.map((c) => {
    const stats = demoCustomerStats[c.id]
    const vehicles = demoVehicles.filter((v) => v.customer_id === c.id)
    return {
      ...c,
      vehicle_count: vehicles.length,
      total_spent: stats?.total_spent ?? 0,
      balance_due: stats?.outstanding ?? 0,
      last_visit: stats?.last_visit ?? null,
      last_visit_status: stats?.outstanding && stats.outstanding > 0 ? "IN SERVICE" : stats?.last_visit ? "COMPLETED" : null,
    }
  })
}

export function getDemoCustomer(id: string): Customer | undefined {
  return demoCustomers.find((c) => c.id === id)
}

export function getDemoVehiclesForCustomer(customerId: string): Vehicle[] {
  return demoVehicles.filter((v) => v.customer_id === customerId)
}

export function getDemoVehicle(id: string): Vehicle | undefined {
  return demoVehicles.find((v) => v.id === id)
}

export function getDemoOrdersForCustomer(customerId: string): (Order & { services_summary: string })[] {
  return demoOrders.filter((o) => o.customer_id === customerId)
}
